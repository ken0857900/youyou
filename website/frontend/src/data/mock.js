export const articlesByCategory = (name) => ARTICLES.filter((a) => a.type === 'article' && a.category === name);
export const articlesByAuthor = (personId, type) => ARTICLES.filter((a) => a.authorId === personId && (!type || a.type === type));
// 热门：按最近 30 天点击人数排（docs/04 定）
export const trending = (type, limit) => ARTICLES.filter((a) => a.type === type).sort((a, b) => b.views30d - a.views30d).slice(0, limit);
// 没后端时的发布：塞进内存数组，刷新就没了（api.publish 的退路）
export const addArticle = (article) => { ARTICLES.unshift(article); return article; };
// 星星数含自己按的那一下（starred 来自 useAppState）
export const starCount = (item, starred) => item.stars + (starred[item.id] ? 1 : 0);

