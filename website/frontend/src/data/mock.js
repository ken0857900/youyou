// 文章里独占一段的图片标记 ![](/uploads/x.jpg)（没后端时是 blob: 网址）。渲染成 <img>；关键词/摘要/原话前要去掉
export const IMG_LINE = /^!\[\]\((\/uploads\/[\w.-]+|blob:[^)\s]+)\)$/;
export const stripImages = (text) => (text || '').split('\n').filter((l) => !IMG_LINE.test(l.trim())).join('\n').replace(/\n{3,}/g, '\n\n').trim();
